#!/usr/bin/env node
/**
 * codegen-migrations.mjs — compile the dev-platform `.sql` migrations into the
 * `.js` modules a plugin ZIP is allowed to carry.
 *
 *     OMADIA_CORE_DIR=../odoo-bot node scripts/codegen-migrations.mjs
 *
 * ## Why a codegen and not just the .sql files
 *
 * `zipExtractor.ts:20-41` allowlists `.yaml .yml .md .json .js .mjs .cjs .map
 * .png .svg .jpg .jpeg .txt .license .html`. **`.sql` is absent** — bug B4 in
 * `implementation.md`, and it means a distributed plugin structurally cannot
 * ship a `.sql` file. D6 answers "codegen or allowlist?" with **both**: the
 * allowlist fix lands in core so the next plugin needs no codegen, and this
 * codegen ships now so THIS plugin does not have to wait for a core release.
 *
 * ## The invariants
 *
 *   - **Filenames are preserved**, `.sql` → `.js`. The migration ledger is keyed
 *     by filename and C11 seeds this plugin's ledger from core's donor rows BY
 *     FILENAME. Rename one file and C11 re-runs a migration that already ran.
 *   - **The SQL inside is byte-identical.** Only three template-literal
 *     metacharacters are escaped on the way in (`\`, a backtick, and `${`), and
 *     `test/migrationSql.test.ts` reverses that escaping and compares the result
 *     against `migrations/checksums.json` — the SHA-256 of each ORIGINAL core
 *     `.sql`. A drifted byte is a red test, not a silent divergence.
 *   - **No renumbering.** `0022`–`0030` keep core's contiguous slot range, per
 *     `core-decoupling-checklist.md` zone 10.
 *
 * Re-run it whenever core's originals change; commit the result.
 */

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const coreDir = resolve(pkgRoot, process.env.OMADIA_CORE_DIR ?? '../../../odoo-bot');
const srcDir = join(coreDir, 'middleware', 'migrations');
const outDir = join(pkgRoot, 'migrations');

/** The nine dev-platform migrations. Named explicitly rather than pattern-matched:
 *  core's directory holds 40+ files and a loose glob would sweep in someone
 *  else's schema the day a `0031_dev_*` lands. */
const FILES = [
  '0022_dev_platform.sql',
  '0023_dev_platform_pipeline.sql',
  '0024_dev_platform_w3.sql',
  '0025_dev_jobs_source_plugin.sql',
  '0026_dev_job_gate_kind.sql',
  '0027_dev_platform_triggers.sql',
  '0028_dev_jobs_webhook_one_active.sql',
  '0029_dev_platform_retention.sql',
  '0030_dev_job_events_truncated_marker.sql',
];

const present = new Set(readdirSync(srcDir));
const missing = FILES.filter((f) => !present.has(f));
if (missing.length > 0) {
  throw new Error(
    `core migrations not found in ${srcDir}: ${missing.join(', ')}. ` +
      'Set OMADIA_CORE_DIR to a core checkout (see CONTRIBUTING.md).',
  );
}

mkdirSync(outDir, { recursive: true });
const checksums = {};

for (const file of FILES) {
  const sql = readFileSync(join(srcDir, file), 'utf8');
  checksums[file] = createHash('sha256').update(sql, 'utf8').digest('hex');
  const escaped = sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  const out = file.replace(/\.sql$/, '.js');
  writeFileSync(
    join(outDir, out),
    `// GENERATED by scripts/codegen-migrations.mjs from middleware/migrations/${file}
// DO NOT EDIT. The SQL between the sentinels is byte-identical to core's file;
// test/migrationSql.test.ts proves it against migrations/checksums.json.
/** @param {{ query: (sql: string) => Promise<unknown> }} client */
export default async (client) => {
  await client.query(\`/*__OMADIA_SQL_BEGIN__*/${escaped}/*__OMADIA_SQL_END__*/\`);
};
`,
  );
  console.log(`  + migrations/${out} (${sql.length} bytes of SQL)`);
}

writeFileSync(join(outDir, 'checksums.json'), `${JSON.stringify(checksums, null, 2)}\n`);
console.log(`✓ ${FILES.length} migrations codegen'd + migrations/checksums.json`);
